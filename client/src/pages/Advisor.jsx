import { useCallback, useEffect, useRef, useState } from 'react';
import { Link, useSearchParams } from 'react-router-dom';
import { Sparkles, Lightbulb, SearchX, RotateCcw } from 'lucide-react';
import { getRecommendations } from '../api/aiApi';
import { getErrorMessage } from '../api/client';
import usePageTitle from '../hooks/usePageTitle';
import AdvisorForm from '../components/ai/AdvisorForm';
import RecommendationCard from '../components/ai/RecommendationCard';
import Spinner from '../components/common/Spinner';
import './Advisor.css';

const MIN_LENGTH = 10;

export default function Advisor() {
  usePageTitle('AI Study Advisor');

  const [searchParams, setSearchParams] = useSearchParams();
  const initialQuestion = searchParams.get('q') || '';
  const [problem, setProblem] = useState(initialQuestion);
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const autoRunDone = useRef(false);

  const runAdvisor = useCallback(async (text) => {
    setError('');

    if (text.trim().length < MIN_LENGTH) {
      setError('Tell the advisor a bit more: what subject, what is hard, and your level.');
      return;
    }

    setLoading(true);
    setResult(null);
    try {
      const data = await getRecommendations(text.trim());
      setResult(data);
    } catch (requestError) {
      setError(getErrorMessage(requestError));
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    if (autoRunDone.current) return;
    autoRunDone.current = true;

    if (initialQuestion.trim().length >= MIN_LENGTH) {
      Promise.resolve().then(() => runAdvisor(initialQuestion));
    }
    if (initialQuestion) {
      setSearchParams({}, { replace: true });
    }
  }, [initialQuestion, runAdvisor, setSearchParams]);

  const handleChange = (value) => {
    setProblem(value);
    setError('');
  };

  const handleSubmit = (event) => {
    event.preventDefault();
    runAdvisor(problem);
  };

  const startOver = () => {
    setResult(null);
    setProblem('');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  return (
    <div className="page container advisor-layout">
      <div className="advisor-hero">
        <span className="advisor-hero-icon">
          <Sparkles size={26} />
        </span>
        <div>
          <h1 className="page-title">AI Study Advisor</h1>
          <p className="page-subtitle">
            Not sure which session you need? Describe what you are struggling with, and the advisor
            will recommend the best matches from our catalog.
          </p>
        </div>
      </div>

      <AdvisorForm
        problem={problem}
        onChange={handleChange}
        onSubmit={handleSubmit}
        loading={loading}
        error={error}
      />

      {loading && (
        <div className="advisor-loading">
          <Spinner label="Reading the catalog and finding your best matches…" />
        </div>
      )}

      {result && (
        <section className="advisor-results" aria-live="polite">
          <p className="advisor-summary">{result.summary}</p>

          {result.recommendations.length > 0 ? (
            result.recommendations.map((recommendation, index) => (
              <RecommendationCard
                key={recommendation.service._id}
                recommendation={recommendation}
                rank={index + 1}
              />
            ))
          ) : (
            <div className="empty-state card">
              <SearchX size={36} />
              <h2>No matching sessions</h2>
              <p>
                Try describing your subject and what you're studying in more detail, or browse every
                session.
              </p>
              <Link to="/services" className="btn btn-secondary">
                Browse all services
              </Link>
            </div>
          )}

          {result.recommendations.length > 0 && result.studyTip && (
            <div className="study-tip">
              <Lightbulb size={20} />
              <p>
                <strong>Study tip:</strong> {result.studyTip}
              </p>
            </div>
          )}

          <div className="advisor-footer">
            <p className="ai-disclaimer">
              Recommendations are generated by AI and can be wrong. Check the session details before
              booking.
            </p>
            <button type="button" className="btn btn-secondary" onClick={startOver}>
              <RotateCcw size={16} /> Ask something else
            </button>
          </div>
        </section>
      )}
    </div>
  );
}
